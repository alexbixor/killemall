def grid(text):
    rows = [r for r in text.splitlines() if r and not r.startswith(';')]
    assert all(len(r) == W for r in rows), [len(r) for r in rows]
    return [list(r) for r in rows]

def fire_frame(idle, flash):
    g = [['.'] * W for _ in range(H)]
    for y in range(H - KICK):
        g[y + KICK] = list(idle[y])
    for y, row in enumerate(flash):
        for x, ch in enumerate(row):
            if ch == '#': g[y][x] = '#'
    return g

def save(name, g, comment):
    rows = [''.join(r) for r in g]
    assert len(rows) == H and all(len(r) == W for r in rows)
    (HERE / f'{name}.txt').write_text(f'; {comment}\n' + '\n'.join(rows) + '\n')
    print(name, len(rows), 'rows')

if __name__ == '__main__':
    p = grid(PISTOL_IDLE); s = grid(SHOTGUN_IDLE)
    assert len(p) == H and len(s) == H
    save('14_pistol_idle', p, 'pistol idle, seen from behind: tapered slide (bore ring at the muzzle, rear sight notch), frame, hollow trigger guard left, grip in a black hand with white finger lines right (generated by _weapon_gen.py)')
