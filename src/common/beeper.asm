; beeper.asm - Kill'em all, 48K sound (lane T3). Beeper SFX + "engine tick" menu tune. Hand Z80, pasmo.
; Contracts (ARCH_M2.md):
;   snd_fx        A = 1 shot, 2 door, 3 pickup, 4 player hurt, 5 enemy die, 6 menu tick, 7 locked/no ammo,
;                 8 enemy attack, 9 level clear, 10 player death. Blocking <= 40 ms (<= 140,000 T), DI inside,
;                 EI on return, honours opt_sfx. Port 254 bit 4 = speaker, border bits always written 0.
;   snd_music     A = 0 stop, 1 menu, 2 game. 48K: only sets/clears snd_playing (honours opt_music) and
;                 rewinds the menu tune. A = 0 also silences the speaker.
;   snd_menu_tick call once per frame from the menu loop: non-blocking, <= 3,000 T with the default knobs
;                 (measured by tools/test_sound.py, numbers in build/t3_report.md). Plays one short burst of a
;                 2-voice square wave per call (voices mixed by time-multiplexing the speaker at ~44 kHz, bit 4
;                 only); voice phases carry over between calls. Steps the 16-bar tune every MT_SPEED frames.
;                 Knobs (bytes, caller may change them): mt_inner (loop passes, 79 T each) and mt_outer (extra
;                 256-pass blocks). Default 27/0 = ~0.6 ms of sound per frame (pitch contour only, buzzy);
;                 mt_outer=2 = ~43,500 T/frame = 12.4 ms of proper 2-voice music per frame.
;   snd_isr       ret (no ISR work on 48K).
; Externals (state.asm / caller): opt_sfx, opt_music (byte, 0 = off).
; Registers: snd_fx, snd_music, snd_menu_tick destroy AF BC DE HL (snd_menu_tick uses AF' but restores it). No IX/IY.
; Stack use: 4 bytes.
; SFX data format (generated by tools/music/gen_beeper.py, see the GENERATED block below):
;   segment = db count, dw period, db slide, db noise_mask ; list ends with db 0.
;   count   = half-cycles (speaker toggles), period = delay loop iterations (26 T each) for one half-cycle,
;   slide   = signed value added to period after every half-cycle, noise_mask = AND mask applied to an 8-bit
;   LFSR value that is added to the period of every half-cycle (0 = pure tone).
;   half-cycle T = 143 (+2 when the LFSR feeds back) + 26*(period + (lfsr & mask)).

snd_isr:
        ret

; ---------------------------------------------------------------- snd_music (48K: flag only)
snd_music:
        ld e,a
        ld a,(opt_music)
        or a
        jr z,snd_mus_off
        ld a,e
        or a
        jr z,snd_mus_off
        ld (snd_playing),a
        ld a,MT_LEN-1
        ld (mt_pos),a           ; first tick advances to step 0
        ld a,1
        ld (mt_cnt),a           ; ... immediately
        ld hl,mt_m1+1
        xor a
        ld (hl),a               ; both voices muted until the first step is fetched
        ld hl,mt_m2+1
        ld (hl),a
        ld (mt_out1),a
        ld (mt_out2),a
        ret
snd_mus_off:
        xor a
        ld (snd_playing),a
        out (254),a             ; speaker off, border 0
        ret

; ---------------------------------------------------------------- snd_fx (blocking beeper SFX)
snd_fx:
        ld e,a
        ld a,(opt_sfx)
        or a
        ret z
        ld a,e
        dec a
        cp 10
        ret nc                  ; unknown id: ignore
        add a,a
        ld hl,sfx_tab
        add a,l
        ld l,a
        jr nc,sfx_t1
        inc h
sfx_t1: ld a,(hl)
        inc hl
        ld h,(hl)
        ld l,a                  ; HL = segment list
        di
        ld c,0                  ; C = speaker byte (0 / 16)
sfx_seg:
        ld a,(hl)               ; count (0 = end of SFX)
        or a
        jr z,sfx_done
        ld b,a
        inc hl
        ld e,(hl)
        inc hl
        ld d,(hl)               ; DE = period
        inc hl
        ld a,(hl)
        ld (sfx_sl+1),a         ; slide (self-modified immediate)
        inc hl
        ld a,(hl)
        ld (sfx_nm+1),a         ; noise mask (self-modified immediate)
        inc hl
        push hl
sfx_half:
        ld a,c
        xor 16
        ld c,a
        out (254),a
        ld a,(sfx_lfsr)         ; 8-bit LFSR (taps 1Dh), period 255
        add a,a
        jr nc,sfx_nx
        xor 1Dh
sfx_nx: ld (sfx_lfsr),a
sfx_nm: and 0
        ld l,a
        ld h,0
        add hl,de               ; HL = period + (lfsr & mask)
sfx_dly:
        dec hl
        ld a,h
        or l
        jr nz,sfx_dly           ; 26 T per iteration
sfx_sl: ld a,0                  ; slide
        ld l,a
        rla
        sbc a,a
        ld h,a
        add hl,de
        ex de,hl                ; DE += slide (signed)
        djnz sfx_half
        pop hl
        jr sfx_seg
sfx_done:
        xor a
        out (254),a             ; speaker off, border 0
        ei
        ret

sfx_lfsr:
        db 1

; ---------------------------------------------------------------- snd_menu_tick (engine tick tune)
; One burst per call. The burst loop alternates the speaker between voice 1's level and voice 2's level every pass
; (79 T, i.e. a ~44 kHz carrier the speaker cannot follow), so the audible output is the SUM of the two square waves.
; Voice counters and levels carry over between calls: the bursts are consecutive slices of the same 2-voice waveform.
; Burst length = mt_inner passes (79 T each, +14 T per voice toggle) + mt_outer * 256 passes.
; Defaults (contract, <= 3,000 T): mt_inner = MT_ITER, mt_outer = 0 -> ~0.7 ms of sound per 20 ms frame: a 50 Hz
; buzz whose spectrum follows the tune (pitch contour only). mt_outer = 2 (~43,500 T, 12.4 ms per frame) gives real
; 2-voice music; the 48K menu loop (no 3D rendering) can afford it - T2/T6 decide.
MT_SPEED equ 12                 ; frames per step (eighth note) -> 125 bpm
MT_ITER  equ 27

snd_menu_tick:
        ld a,(snd_playing)
        or a
        ret z
        ld a,(opt_music)
        or a
        jr z,snd_mus_off        ; option switched off while playing: stop + silence
        ld hl,mt_cnt
        dec (hl)
        jr nz,mt_burst
        ld (hl),MT_SPEED
        ld a,(mt_pos)
        inc a
        cp MT_LEN
        jr c,mt_pos_ok
        xor a
mt_pos_ok:
        ld (mt_pos),a
        ld hl,mt_mel            ; voice 1: one counter byte per 1/8 (0 = rest)
        call mt_addhl
        ld a,(hl)
        ld de,mt_p1
        ld hl,mt_m1+1
        call mt_setnote
        ld a,(mt_pos)
        srl a                   ; voice 2: one counter byte per 1/4
        ld hl,mt_v2
        call mt_addhl
        ld a,(hl)
        ld de,mt_p2
        ld hl,mt_m2+1
        call mt_setnote
mt_burst:
        ld hl,mt_p1
        ld a,(hl)
        inc hl
        ld c,(hl)
        inc hl
        ld d,(hl)
        inc hl
        ld e,(hl)
        inc hl
        ld h,a                  ; H = period 1, C = counter 1, D = period 2, E = counter 2
        ld a,(mt_out1)
        ld l,a                  ; L = voice 1 level (0 / 16)
        ex af,af'
        push af                 ; preserve the caller's AF'
        ld a,(mt_out2)          ; A' = voice 2 level (0 / 16)
        ex af,af'
        ld a,(mt_outer)
        ld (mt_oc),a
        ld a,(mt_inner)
        ld b,a
mt_lp:  dec c                   ; voice 1 counter          4
        jr nz,mt_l1             ;                          12/7
        ld c,h
        ld a,l
mt_m1:  xor 16                  ; 16 = sounding, 0 = rest (self-modified)
        ld l,a
mt_l1:  ld a,l                  ;                          4
        out (254),a             ; voice 1 slot             11
        dec e                   ; voice 2 counter          4
        jr nz,mt_l2             ;                          12/7
        ld e,d
        ex af,af'
mt_m2:  xor 16
        ex af,af'
mt_l2:  ex af,af'               ;                          4
        out (254),a             ; voice 2 slot             11
        ex af,af'               ;                          4
        djnz mt_lp              ;                          13/8  -> 79 T per pass without toggles
        ld a,(mt_oc)            ; extra 256-pass blocks (default 0)
        or a
        jr z,mt_end
        dec a
        ld (mt_oc),a
        jr mt_lp                ; B = 0 -> 256 more passes
mt_end: ld a,c
        ld (mt_c1),a
        ld a,e
        ld (mt_c2),a
        ld a,l
        ld (mt_out1),a
        ex af,af'
        ld (mt_out2),a
        pop af
        ex af,af'
        ret

mt_addhl:                       ; HL = HL + A
        add a,l
        ld l,a
        ret nc
        inc h
        ret

mt_setnote:                     ; A = counter (0 = rest), DE -> period slot (+1 = counter), HL -> xor mask slot
        or a
        jr z,mt_rest
        ld (hl),16
        ld (de),a
        inc de
        ld a,1
        ld (de),a               ; counter = 1 -> the new note starts on the first pass
        ret
mt_rest:
        ld (hl),a               ; mask 0: the voice stays silent (counter keeps running, harmless)
        ret

snd_playing:
        db 0
mt_pos: db 0
mt_cnt: db 1
mt_p1:  db 2                    ; keep the 4 bytes mt_p1, mt_c1, mt_p2, mt_c2 contiguous (mt_burst reads them in order)
mt_c1:  db 1
mt_p2:  db 2
mt_c2:  db 1
mt_out1:
        db 0
mt_out2:
        db 0
mt_oc:  db 0
mt_inner:
        db MT_ITER
mt_outer:
        db 0

