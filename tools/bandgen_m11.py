#!/usr/bin/env python3
"""bandgen_m11.py - M1.1 speed-pass code generator (called from gen48.py; emits src/48k/gen/bands48.asm + tables).

Design (all addresses are the column-major back buffer BUF = 24576, 16 columns x 128 stride, row = L low 7 bits):
  * TEX4: textures pre-shifted into 4 copies, one per 2-px position p (0..3) inside a byte: byte = texel ? (192 >> 2p) : 0.
    Page layout per (page, p): 256 bytes, index u*16 + v.  So a band row is: ld a,(de) / or (hl) / ld (hl),a / inc l  = 7+7+7+4.
  * One unrolled band routine per wall height h (2..96 even, odd heights are made even by the height table):
    the v-step for height h is a compile-time constant, so the per-row 'add hl,bc / ld e,h' in the alternate set is
    replaced by: rows where v does not change -> no texel reload (same E), rows where v changes -> 'inc e' (v step 1) or
    'ld a,e / add a,k / ld e,a' when the step is >= 2 (v in low nibble, u*16 in the high nibble; v never wraps inside a band).
    No exx per row, no mask, no shifts.  Entry: HL = buffer address of the top row, DE = TEX4 page + u*16 + v0 (v0 = 0).
  * Clipped routines for virtual heights > 96 (very near walls): the visible 96 rows show the middle part of the texture;
    generated for heights 98..192 step 2 (48 routines) with v precomputed per row.
  * CLRBUF: fills the 16 columns of the buffer: rows 0..47 zero, 48..95 the floor checker (0xAA/0x55 alternating rows),
    using PUSH (SP-based, 2 bytes per 11 T) -- 768 pushes + setup.  Interrupts can stay on (ISR pushes go below SP
    into bytes that have been written already... NO: pushes go downwards into unfilled bytes.  So CLRBUF runs with the
    fill going from high addresses to low: column 15 row 95 first.  The ISR return addresses land in not-yet-filled
    buffer bytes which are overwritten afterwards; that is harmless.)
  * COPYBUF: as in M1.1a (pop/ld (hl) burst, interrupts on).
"""
import pathlib

def band_rows(h):
    """Per-row texture v (0..15) for a wall h rows high (h <= 96): v = (r * 16) // h, same mapping as the M1 STEPTAB
    accumulator (v = int(r * 4096 / h) >> 8) so that chk48's geometry stays identical."""
    return [((r * (4096 // h)) >> 8) & 15 for r in range(h)]

def clipped_rows(hv):
    """Virtual height hv > 96: 96 visible rows, texture rows centred."""
    top = (hv - 96) // 2
    return [((r * (4096 // hv)) >> 8) & 15 for r in range(top, top + 96)]

def emit_band(label, vs):
    s = [label + ":"]
    prev = None
    for v in vs:
        if prev is None:
            pass                                    # entry: E already = u*16 + v0 (v0 = vs[0]); caller sets it
        elif v != prev:
            d = v - prev
            if d == 1:
                s.append("        inc e")
            else:
                s.extend(["        ld a,e", "        add a,%d" % d, "        ld e,a"])
        s.extend(["        ld a,(de)", "        or (hl)", "        ld (hl),a", "        inc l"])
        prev = v
    s.append("        ret")
    return s

def bands():
    s = ["; generated by tools/bandgen_m11.py - do not edit",
         "; BAND_h: OR-blit of an h-row textured band.  HL = buffer addr of top row, DE = TEX4 page + u*16 + v0.  Trashes A, E."]
    table = []
    for h in range(2, 97, 2):
        s += emit_band("BAND_%d" % h, band_rows(h))
    for hv in range(98, 193, 2):
        s += emit_band("BANDC_%d" % hv, clipped_rows(hv))
    # dispatch table indexed by hcol/2 (hcol = 0,2,..,192): word address; hcol 0 -> BAND_NONE (ret)
    s.append("BAND_NONE:")
    s.append("        ret")
    entries = ["BAND_NONE"] + ["BAND_%d" % h for h in range(2, 97, 2)] + ["BANDC_%d" % hv for hv in range(98, 193, 2)]
    s.append("BANDTAB:")
    for i in range(0, len(entries), 8):
        s.append("        defw " + ",".join(entries[i:i + 8]))
    # v0 per height (first row's v, always 0 for h <= 96; for clipped heights the centred start v)
    v0 = [0] + [band_rows(h)[0] for h in range(2, 97, 2)] + [clipped_rows(hv)[0] for hv in range(98, 193, 2)]
    s.append("BANDV0:")
    for i in range(0, len(v0), 16):
        s.append("        defb " + ",".join(str(v) for v in v0[i:i + 16]))
    return s

def clrbuf():
    """Fill the buffer with PUSH: SP walks down from BUF+16*128 (=26624) to BUF.  Column c occupies BUF+c*128 .. +127:
    rows 96..127 unused (32 bytes, still pushed as zero - 16 pushes), rows 95..48 floor (24 pushes), rows 47..0 zero (24
    pushes).  So per column: 16 pushes of 0, 24 pushes of floor pair, 24 pushes of 0.  Floor rows: row 48 even -> 0xAA,
    row 49 -> 0x55; a push writes (SP-1) = high byte (odd row) and (SP-2) = low byte (even row): push DE with
    D = 0x55 (odd rows), E = 0xAA (even rows)."""
    s = ["CLRBUF:", "        ld (cl_sp+1),sp", "        ld sp,BUF+2048", "        ld hl,0", "        ld de,%d" % (0x55 * 256 + 0xAA)]
    for c in range(16):
        s += ["        push hl"] * 16 + ["        push de"] * 24 + ["        push hl"] * 24
    s += ["cl_sp:  ld sp,0", "        ret"]
    return s

def scr_addr(y):
    return 0x4000 + ((y & 0xC0) << 5) + ((y & 7) << 8) + ((y & 0x38) << 2)

def copybuf():
    s = ["COPYBUF:", "        ld (cb_sp+1),sp"]
    for c in range(16):
        s.append("        ld sp,BUF+%d" % (c * 128))
        for r in range(0, 96, 2):
            s.append("        pop de")
            if r == 0:
                s.append("        ld hl,%d" % (scr_addr(8) + 8 + c))
            else:
                d = (scr_addr(8 + r) + 8 + c) - (scr_addr(8 + r - 1) + 8 + c)
                if d == 256:
                    s.append("        inc h")
                else:
                    s.append("        ld hl,%d" % (scr_addr(8 + r) + 8 + c))
            s.append("        ld (hl),e")
            s.append("        inc h")
            s.append("        ld (hl),d")
    s += ["cb_sp:  ld sp,0", "        ret"]
    return s

def tex4(texture_pages_fn):
    """From the 9 lit + 9 dark 16x16 pages (values 0/255 or 0/0xAA) build 4 pre-shifted copies: TEX4 + (page*4 + p)*256.
    Dark pages: the 0xAA stripe pattern must stay aligned to absolute screen x, so copy p keeps the bits of 0xAA that fall
    inside its 2-px slot (slot p covers bits 7-2p and 6-2p: for 0xAA (10101010) the lit bit is the even x -> the left pixel
    of every 2-px pair => every dark slot shows '10' = (128 >> 2p))."""
    pages = texture_pages_fn()
    out = []
    for pg in range(18):
        src = pages[pg * 256:(pg + 1) * 256]
        for p in range(4):
            for b in src:
                if b == 0:
                    out.append(0)
                elif b == 0xFF:
                    out.append(192 >> (2 * p))
                else:                                   # 0xAA dark
                    out.append(128 >> (2 * p))
    return out

