#!/usr/bin/env python3
"""lev128.py - bank-1 level images + the relocated low code block for the 128K edition (lane T4; lane K1 6 Nov 2026).
LEVELS8 (default, every 128K build): the EIGHT mapc levels (assets/levels/01..08, `mapc.py 128k`) in the exact layout the
engine's level_data slot uses (byte 0 = level id 1..8, then header + 1024 cells + things, zero-padded to LEVEL_BLK = 1 + 8 +
1024 + 3 * 36 = 1141 bytes) -> build/lev128_{0..7}.bin, plus the low code block (src/128k/lowcode128.asm = lowcode.asm at
LOWCODE 5BC0h) -> build/lowcode128.bin/.sym, and the generated includes src/128k/gen/lev128_sizes.asm (LEV_STRIDE, NLEV,
LOWCODE, LOWCODE_LEN for bank1.asm) + src/128k/gen/lowcode128_equ.asm (the block's symbols for the engine, kea48.asm).
usage: lev128.py [--hires]              pass 1 (before the engine is assembled; hr_pass externals = 0)
       lev128.py [--hires] --fix SYM    pass 2: re-assemble the block with the engine's fl_wait/BANKM/fl_pg0/draw_sprite
                                        from SYM and assert the symbol layout did not move (then bank1.asm is assembled)
       lev128.py --legacy               the pre-K1 set: 3 levels, LEVEL_BLK 1081, no low code block
"""
import subprocess, sys, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[1]
PY = str(ROOT / ".venv/bin/python")
ALL = ["01_entry.txt", "02_barracks.txt", "03_furnace.txt", "04_crypt.txt", "05_cistern.txt", "06_armoury.txt",
       "07_gallery.txt", "08_throne.txt"]
LOWCODE, CMIN = 0x5BC0, 0x5D20          # state.asm LOWCODE / CMIN (DRAM + 20h); tools/test_k1.py asserts both against the .sym
GEN = ROOT / "src/128k/gen"; GEN.mkdir(exist_ok=True)
BUILD = ROOT / "build"

def sym(path):
    return {m.group(1): int(m.group(2), 16) for m in re.finditer(r"^(\w+)\s+EQU\s+0?([0-9A-F]+)H", pathlib.Path(path).read_text(), re.M)}

def levels(names, nthings, edition):
    blk = 1 + 8 + 1024 + 3 * nthings
    sizes = []
    for i, name in enumerate(names):
        out = BUILD / ("level%02d.bin" % (i + 1))
        r = subprocess.run([PY, str(ROOT / "tools/mapc.py"), edition, str(out), str(ROOT / "assets/levels" / name)],
                           capture_output=True, text=True)
        if r.returncode:
            sys.exit("mapc failed for %s: %s" % (name, r.stdout + r.stderr))
        d = out.read_bytes()
        assert d[0] == 1 and d[1] == 75 and len(d) <= blk and d[8] <= nthings, "unexpected mapc output for %s" % name
        (BUILD / ("lev128_%d.bin" % i)).write_bytes((bytes([i + 1]) + d[1:]).ljust(blk, b"\0"))   # same bytes mklevelblk.py would emit
        sizes.append(len(d))
    return blk, sizes

def asm_lowcode(hires, ext):
    equs = ["--equ", "LEVELS8=1", "--equ", "LOWCODE=%d" % LOWCODE, "--equ", "CMIN=%d" % CMIN]
    if hires:
        equs += ["--equ", "HIRES=1"]
    for k, v in ext.items():
        equs += ["--equ", "%s=%d" % (k, v)]
    r = subprocess.run(["pasmo"] + equs + ["--bin", "lowcode128.asm", "../../build/lowcode128.bin", "../../build/lowcode128.sym"],
                       cwd=ROOT / "src/128k", capture_output=True, text=True)
    if r.returncode:
        sys.exit("pasmo lowcode128.asm failed: %s" % (r.stdout + r.stderr))
    S = sym(BUILD / "lowcode128.sym")
    n = len((BUILD / "lowcode128.bin").read_bytes())
    assert S["lowcode_start"] == LOWCODE and S["lowcode_len"] == n and S["low_end"] == LOWCODE + n, (S, n)
    return S, n

EXT_KEYS = ("fl_wait", "BANKM", "fl_pg0", "draw_sprite")

def main():
    args = sys.argv[1:]
    hires = "--hires" in args
    if "--legacy" in args:
        blk, sizes = levels(ALL[:3], 16, "48k")
        (GEN / "lev128_sizes.asm").write_text("; generated by tools/lev128.py --legacy - do not edit\nLEV_STRIDE equ %d   ; level_data slot size: id + header + 1024 cells + 16 things\nNLEV equ 3\n" % blk)
        print("lev128 (legacy): mapc sizes", sizes, "block", blk); return
    if "--fix" in args:
        # pass 2: the engine exists -> real external addresses; the block's own layout must be the one pass 1 published
        eng = sym(args[args.index("--fix") + 1])
        before = sym(BUILD / "lowcode128.sym")
        ext = {k: eng[k] for k in EXT_KEYS if k in eng} if hires else {}
        S, n = asm_lowcode(hires, ext)
        moved = [k for k in before if k not in EXT_KEYS and before[k] != S.get(k)]
        if moved:
            sys.exit("lev128 --fix: low code block symbols moved between pass 1 and pass 2: %s" % moved)
        print("lev128 --fix: low code block re-assembled with %s, %d B at %04Xh, layout unchanged" % (
            ", ".join("%s=%04Xh" % (k, v) for k, v in ext.items()) or "no externals", n, LOWCODE))
        return
    blk, sizes = levels(ALL, 36, "128k")
    S, n = asm_lowcode(hires, {k: 0 for k in EXT_KEYS} if hires else {})
    (GEN / "lev128_sizes.asm").write_text(
        "; generated by tools/lev128.py (lane K1) - do not edit\n"
        "LEV_STRIDE equ %d   ; level_data slot size: id + header + 1024 cells + 36 things (LEVELS8)\n"
        "NLEV equ 8\n"
        "LOWCODE equ %d      ; run-time address of the low code block (state.asm)\n"
        "LOWCODE_LEN equ %d  ; bytes b1_load copies there (build/lowcode128.bin)\n" % (blk, LOWCODE, n))
    skip = {"lowcode_start", "lowcode_len", "low_end", "LOWCODE", "CMIN", "HIRES", "LEVELS8"} | set(EXT_KEYS)
    lines = ["; generated by tools/lev128.py (lane K1) from build/lowcode128.sym - do not edit. The low code block",
             "; (src/common/lowcode.asm) runs at LOWCODE 5BC0h on the 128K (LEVELS8): copied from bank 1 by b1_load (bank1.asm).",
             "LOWCODE_LEN equ %d" % n]
    lines += ["%s equ 0%04Xh" % (k, v) for k, v in sorted(S.items(), key=lambda kv: kv[1]) if k not in skip]
    (GEN / "lowcode128_equ.asm").write_text("\n".join(lines) + "\n")
    print("lev128: mapc sizes", sizes, "block", blk, "| low code block %d B at %04Xh..%04Xh%s" % (n, LOWCODE, LOWCODE + n - 1, " (HIRES)" if hires else ""))

if __name__ == "__main__":
    main()
