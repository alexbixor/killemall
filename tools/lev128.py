#!/usr/bin/env python3
"""lev128.py - build the bank-1 level images for the 128K edition: the three mapc levels in the exact layout the
engine's level_data slot uses (tools/mklevelblk.py: byte 0 = level id 1..3, then header + 1024 cells + things,
zero-padded to LEVEL_BLK = 1081 bytes). Writes build/lev128_{0,1,2}.bin + src/128k/gen/lev128_sizes.asm."""
import subprocess, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
PY = str(ROOT / ".venv/bin/python")
SRC = ["01_entry.txt", "02_barracks.txt", "03_furnace.txt"]
LEVEL_BLK = 1 + 8 + 1024 + 3 * 16
(ROOT / "src/128k/gen").mkdir(exist_ok=True)
sizes = []
for i, name in enumerate(SRC):
    out = ROOT / "build" / ("level%02d.bin" % (i + 1))
    r = subprocess.run([PY, str(ROOT / "tools/mapc.py"), "48k", str(out), str(ROOT / "assets/levels" / name)],
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit("mapc failed for %s: %s" % (name, r.stdout + r.stderr))
    d = out.read_bytes()
    assert d[0] == 1 and d[1] == 75 and len(d) <= LEVEL_BLK, "unexpected mapc output for %s" % name
    blk = (bytes([i + 1]) + d[1:]).ljust(LEVEL_BLK, b"\0")      # same bytes mklevelblk.py would emit
    (ROOT / "build" / ("lev128_%d.bin" % i)).write_bytes(blk)
    sizes.append(len(d))
(ROOT / "src/128k/gen/lev128_sizes.asm").write_text(
    "; generated by tools/lev128.py - do not edit\nLEV_STRIDE equ %d   ; level_data slot size: id + header + 1024 cells + 16 things\n" % LEVEL_BLK)
print("lev128: mapc sizes", sizes, "block", LEVEL_BLK)
