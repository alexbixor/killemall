#!/usr/bin/env python3
"""m22_pixdata.py - generate src/common/dash_data.asm (low block, 167 B) for the M2.2 dashboard from the approved mockup
geometry (tools/m22_mockup.py v5, labels/pips shifted to byte-aligned x: AMMO panel flush left, 10 pips at x = 1 + 8k):
  DASH_RUNS   runs (addr, count, byte): static pixel lines (top frame line, rail) then the attribute map; addr 0 ends
  DASH_LABELS (addr, text, 0) bold labels; addr 0 terminator
  PILLS       4 x (8 rows x 2 bytes): R held, R missing, B held, B missing (16 x 8 rounded pills, ROM font letter)
and prints the pip bitmaps (pistol pip: lead head rows y130..135 + brass case y136..142, 5 px at bits 6..2) to paste into
src/common/hud_b.asm (PIPFULL/PIPEMPTY, 26 B, high block). Pure PIL, no emulator."""
from PIL import Image, ImageDraw

ROM = open('tools/zesarux/48.rom', 'rb').read()
def glyph(ch):
    o = 0x3D00 + (ord(ch) - 32) * 8
    return list(ROM[o:o + 8])

def pill_bytes(letter, held):
    img = Image.new('1', (16, 8), 0)
    d = ImageDraw.Draw(img)
    px = img.load()
    if held:
        d.rounded_rectangle([0, 0, 15, 7], radius=4, fill=1)
        for r, b in enumerate(glyph(letter)):
            for i in range(8):
                if b & (128 >> i):
                    px[4 + i, r] = 0
    else:
        d.rounded_rectangle([0, 0, 15, 7], radius=4, outline=1)
        for r, b in enumerate(glyph(letter)):
            for i in range(8):
                if b & (128 >> i) and 1 <= r <= 6:
                    px[4 + i, r] = 1
    out = []
    for r in range(8):
        v = 0
        for x in range(16):
            v = (v << 1) | (1 if px[x, r] else 0)
        out += [v >> 8, v & 255]
    return out

pills = []
for letter in "RB":
    for held in (1, 0):
        pills += pill_bytes(letter, held)

def attr(row, col):
    return 22528 + 32 * row + col
RED, BLUE, CYAN, YELLOW = 2, 1, 5, 6
runs = [(0x4703, 1, 0x01), (0x4704, 24, 0xFF), (0x471C, 1, 0x80),   # pixels: frame top line y 7, x 31..224 (M2.5C)
        (0x48A0, 32, 0xFF),          # pixels: rail y 104, full width
        (attr(0, 3), 26, RED),       # frame top line y 7 (cols 3..28, M2.5C)
        (attr(13, 0), 32, RED),      # rail y 104
        (attr(14, 0), 4, RED),       # AMMO
        (attr(14, 11), 6, RED),      # HEALTH
        (attr(14, 22), 4, RED),      # KEYS
        (attr(16, 22), 2, RED),      # pill R
        (attr(16, 25), 2, BLUE),     # pill B
        (attr(17, 0), 10, YELLOW),   # pip cases
        (attr(18, 11), 6, RED),      # SHIELD
        (attr(18, 22), 5, RED),      # KILLS
        (attr(20, 11), 9, CYAN),     # shield bar rows 20-21
        (attr(21, 11), 9, CYAN)]
def pix(y, col):
    return 0x4000 + (y & 0xC0) * 32 + (y & 7) * 256 + (y & 0x38) * 4 + col
labels = [(pix(112, 0), "AMMO"), (pix(112, 11), "HEALTH"), (pix(112, 22), "KEYS"),
          (pix(144, 11), "SHIELD"), (pix(144, 22), "KILLS"), (pix(152, 0), "PISTOL")]
assert pix(112, 0) == 18624 and pix(144, 0) == 20544 and pix(176, 0) == 20672, "row address formula"

s = ["; dash_data.asm - generated by tools/m22_pixdata.py (M2.2 dashboard data, low block) - do not edit",
     "DASH_RUNS:"]
for a, n, c in runs:
    s.append("        defw %d" % a)
    s.append("        defb %d,%d" % (n, c))
s.append("        defw 0")
s.append("DASH_LABELS:")
for a, t in labels:
    s.append("        defw %d" % a)
    s.append('        defb "%s",0' % t)
s.append("        defw 0")
s.append("PILLS:")
for k in range(4):
    s.append("        defb " + ",".join(str(b) for b in pills[16 * k:16 * k + 16]))
open('src/common/dash_data.asm', 'w').write("\n".join(s) + "\n")
size = 4 * len(runs) + 2 + sum(2 + len(t) + 1 for _, t in labels) + 2 + 64
print("wrote src/common/dash_data.asm: %d bytes" % size)

HEAD = ["..#..", ".###.", "#####", "#####", "#####", "#####"]
HEAD_EMPTY = ["..#..", ".#.#.", "#...#", "#...#", "#...#", "#...#"]
CASE = ["#####"] * 7
CASE_EMPTY = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"]
def bits(rowstr):
    return int("".join("1" if c == "#" else "0" for c in rowstr), 2) << 2      # 5 px at x = 1..5 of the byte
full = [bits(r) for r in HEAD + CASE]
empty = [bits(r) for r in HEAD_EMPTY + CASE_EMPTY]
print("PIPFULL:  defb " + ",".join("%d" % b for b in full))
print("PIPEMPTY: defb " + ",".join("%d" % b for b in empty))
# bar fill: f = 70*v/100 approximated in Z80 by (v*180) >> 8; report the worst error
err = [(v, 70 * v // 100, (v * 180) >> 8) for v in range(101) if 70 * v // 100 != (v * 180) >> 8]
print("bar fill (v*180)>>8 vs 70v/100: %d values off by one px: %s" % (len(err), err[:6]))
