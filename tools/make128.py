#!/usr/bin/env python3
"""make128.py - MECHANICAL transformer src/48k/kea48.asm -> src/128k/kea128_gen.asm (never hand-edit the output).
Anchors (everything else is copied byte-for-byte; tools/test_128.py asserts the diff is exactly these):
 A1 `start:`  -> `call bank_init` becomes the first instruction (page bank 0, BANKM consistent).
 A2 `isr:`    -> `call snd_isr` becomes the first ISR instruction (snd_isr saves AF BC DE HL itself) unless present.
 A3 the `include "../common/beeper.asm"` line is removed and `include "../128k/shim128.asm"` is inserted before the
    FIRST include line of the file (= end of the hand-written part, ~35.5K: the shim must sit below 49152 because it
    runs while bank 1 is paged in; the beeper include position is above 49152). Paths are CWD-relative (pasmo), and
    kea128_gen.asm is assembled with CWD = src/48k so T1/T6's own include paths keep working.
 A4 T6's tape level loader label `load_level:` is renamed `load_level_tape:` so `call load_level` (new_game in kea48.asm,
    lc_next in game_d.asm) resolves to the shim's bank-1 copy; its contract (A = level id 1..3) is unchanged.
 A5 `xor a` + `call snd_music` right after the `call fe_run` of the main menu (stop music on START) becomes `ld a,2`
    (AY game track; the 48K build has no in-game music by contract).
usage: make128.py [in.asm] [out.asm]   (defaults: src/48k/kea48.asm -> src/128k/kea128_gen.asm); exit 1 if an anchor is
missing (prints which), so a silently broken 128K build cannot happen."""
import sys, re, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
SHIM_INC = '        include "../128k/shim128.asm"'

def transform(text):
    lines = text.split("\n")
    out, notes = [], []
    first_inc_done = isr_has_call = False
    isr_idx = None
    # look ahead: does the ISR body already call snd_isr?
    for i, l in enumerate(lines):
        if re.match(r"^isr:", l):
            isr_idx = i
            for m in lines[i:i + 40]:
                if re.search(r"\bcall\s+snd_isr\b", m): isr_has_call = True
                if re.search(r"\breti\b", m): break
            break
    fe_seen = a5_done = False
    i = 0
    while i < len(lines):
        l = lines[i]
        m = re.match(r"^start:(\s*)(.*)$", l)
        if m:
            out.append("start:  call bank_init         ; T4 128K anchor A1")
            if m.group(2).strip(): out.append("        " + m.group(2).strip())
            notes.append("A1 start"); i += 1; continue
        m = re.match(r"^isr:(\s*)(.*)$", l)
        if m and not isr_has_call:
            out.append("isr:    call snd_isr           ; T4 128K anchor A2 (AY player tick in bank 1)")
            if m.group(2).strip(): out.append("        " + m.group(2).strip())
            notes.append("A2 isr"); i += 1; continue
        if re.match(r'^\s*include\s+"', l) and not first_inc_done:
            out.append(SHIM_INC + "   ; T4 128K anchor A3 (below 49152)")
            first_inc_done = True; notes.append("A3 shim include")
        if re.match(r'^\s*include\s+".*beeper\.asm"', l):
            out.append("; T4 128K anchor A3: beeper.asm removed (AY player in bank 1 via shim128.asm)")
            notes.append("A3 beeper removed"); i += 1; continue
        m = re.match(r"^load_level:(.*)$", l)
        if m:
            out.append("load_level_tape:" + m.group(1) + "   ; T4 128K anchor A4 (shim load_level copies from bank 1)")
            notes.append("A4 load_level"); i += 1; continue
        if re.search(r"\bcall\s+fe_run\b", l): fe_seen = True
        if fe_seen and not a5_done and re.match(r"^\s*xor\s+a\s*(;.*)?$", l) and i + 1 < len(lines) \
                and re.search(r"\bcall\s+snd_music\b", lines[i + 1]):
            out.append("        ld a,2                 ; T4 128K anchor A5: AY game track instead of stop")
            a5_done = True; notes.append("A5 game track"); i += 1; continue
        out.append(l); i += 1
    missing = [a for a in ("A1 start", "A2 isr", "A3 shim include", "A3 beeper removed", "A4 load_level", "A5 game track")
               if a not in notes and not (a == "A2 isr" and isr_has_call)]
    return "\n".join(out), notes, missing

def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "src/48k/kea48.asm"
    dst = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "src/128k/kea128_gen.asm"
    text = src.read_text()
    out, notes, missing = transform(text)
    head = "; kea128_gen.asm - GENERATED by tools/make128.py from %s - DO NOT EDIT (anchors: %s)\n" % (src.name, ", ".join(notes))
    dst.write_text(head + out)
    print("make128: %s -> %s, anchors: %s" % (src, dst, ", ".join(notes)))
    if missing:
        print("make128: MISSING anchors:", ", ".join(missing)); sys.exit(1)

if __name__ == "__main__":
    main()
