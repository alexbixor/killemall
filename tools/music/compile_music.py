#!/usr/bin/env python3
"""compile_music.py - T3: compile tools/music/track_*.py (Python note data) into src/gen/music_data.asm (KAM1 format,
see FORMAT.md). Also writes build/music_model.json (per-frame expected channel state used by tools/test_sound.py).

usage: compile_music.py            -> src/gen/music_data.asm
"""
import importlib, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
OUT = ROOT / "src/gen/music_data.asm"
AY_CLOCK = 1_773_400
NOTE_NAMES = {"C": 0, "C#": 1, "DB": 1, "D": 2, "D#": 3, "EB": 3, "E": 4, "F": 5, "F#": 6, "GB": 6, "G": 7,
              "G#": 8, "AB": 8, "A": 9, "A#": 10, "BB": 10, "B": 11}

def note_number(tok):
    """'C-4' / 'C#4' / 'Db4' -> 1..95 (12*(oct-1) + semitone + 1); octave 1..8."""
    m = re.fullmatch(r"([A-Ga-g])([-#bB]?)(\d)", tok)
    if not m:
        raise ValueError("bad note %r" % tok)
    name = m.group(1).upper() + ("" if m.group(2) in ("", "-") else m.group(2).upper())
    n = 12 * (int(m.group(3)) - 1) + NOTE_NAMES[name] + 1
    if not 1 <= n <= 0x5F:
        raise ValueError("note out of range %r" % tok)
    return n

def ay_period(n):
    f = 440.0 * 2 ** ((n - 46) / 12)           # n = 46 -> A4 (12*3 + 9 + 1); n = 1 -> C1 = 32.7 Hz
    return max(1, min(4095, round(AY_CLOCK / (16 * f))))

def parse_channel(text, rows_total):
    """Return a list of rows; each row = dict(inst, arp, slide, note) where note = int (on), 'off', or None (hold)."""
    rows = [dict(note=None) for _ in range(rows_total)]
    pos = 0
    inst = arp = slide = None
    for tok in text.replace("|", " ").split():
        if tok.startswith("@"):
            inst = int(tok[1:]); continue
        if tok.startswith("arp"):
            arp = int(tok[3:], 16); continue
        if tok.startswith("sl"):
            slide = int(tok[2:]); continue
        if "*" in tok:
            name, dur = tok.split("*"); dur = int(dur)
        else:
            name, dur = tok, 1
        if pos + dur > rows_total:
            raise ValueError("channel overflow at token %r (pos %d)" % (tok, pos))
        if name == "-":
            pass
        elif name == "r":
            rows[pos]["note"] = "off"
        else:
            r = rows[pos]
            r["note"] = note_number(name)
            if inst is not None: r["inst"] = inst; inst = None
            if arp is not None: r["arp"] = arp; arp = None
            if slide is not None: r["slide"] = slide; slide = None
        pos += dur
    if pos != rows_total:
        raise ValueError("channel has %d rows, expected %d" % (pos, rows_total))
    return rows

def encode_pattern(rows):
    """rows -> bytes (stream tokens, exactly len(rows) rows)."""
    out = bytearray(); empty = 0
    def flush():
        nonlocal empty
        while empty:
            k = min(empty, 31); out.append(0x60 + k); empty -= k
    for r in rows:
        if r["note"] is None:
            empty += 1; continue
        flush()
        if "inst" in r: out.append(0x80 + r["inst"])
        if r.get("arp"): out += bytes([0x90, r["arp"]])          # a note-on without prefix clears arp/slide anyway
        if r.get("slide"): out += bytes([0x91, r["slide"] & 0xFF])
        out.append(0x60 if r["note"] == "off" else r["note"])
    flush()
    return bytes(out)

def compile_song(song):
    rows_pp = song["rows"]; bars = song["bars"]; rows_total = bars * 16
    if rows_total % rows_pp:
        raise ValueError("bars*16 not a multiple of rows per pattern")
    if song["speed"] < 4:
        print("warning: %s speed %d < 4 -> the player decodes channels B/C in a catch-up on the row frame (heavier ISR)" % (song["name"], song["speed"]))
    chans = [parse_channel(c, rows_total) for c in song["channels"]]
    n_pat = rows_total // rows_pp
    streams = {}; order = []; pat_defs = []
    for p in range(n_pat):
        key = []
        for ch in range(3):
            data = encode_pattern(chans[ch][p * rows_pp:(p + 1) * rows_pp])
            if data not in streams:
                streams[data] = "%s_s%d" % (song["name"], len(streams))
            key.append(streams[data])
        key = tuple(key)
        if key not in pat_defs:
            pat_defs.append(key)
        order.append(pat_defs.index(key))
    insts = []
    for name, mix, loop, env in song["instruments"]:
        if not 1 <= len(env) <= 255 or not 0 <= loop < len(env):
            raise ValueError("instrument %s envelope/loop" % name)
        insts.append((name, mix, loop, env))
    return dict(name=song["name"], speed=song["speed"], rows=rows_pp, order=order, loop=song["loop_bar"] * 16 // rows_pp,
                streams=streams, patterns=pat_defs, insts=insts, rows_total=rows_total, chans=chans)

def emit(songs):
    L = ["; music_data.asm - GENERATED by tools/music/compile_music.py (format: tools/music/FORMAT.md). Do not edit.",
         "ay_notes:   ; 12-bit tone periods, index = note number (0 unused; 96..127 = headroom for instrument/arp offsets), AY clock 1773400 Hz"]
    per = [0] + [ay_period(n) for n in range(1, 128)]
    for i in range(0, 128, 16):
        L.append("        dw " + ",".join(str(p) for p in per[i:i + 16]))
    sizes = {}
    for s in songs:
        n = s["name"]; start_label = "music_%s" % n
        L.append("%s:" % start_label)
        L.append("        db %d,%d" % (s["speed"], s["rows"]))
        L.append("        dw %s_order,%s_pats,%s_insts" % (n, n, n))
        L.append("%s_order:" % n)
        L.append("        db " + ",".join(str(o) for o in s["order"]) + ",0FFh,%d" % s["loop"])
        L.append("%s_pats:" % n)
        for key in s["patterns"]:
            L.append("        dw %s,%s,%s" % key)
        L.append("%s_insts:" % n)
        names = ["%s_i%d" % (n, i) for i in range(len(s["insts"]))]
        L.append("        dw " + ",".join((names + [names[0]] * 16)[:16]))
        for lbl, (iname, mix, loop, env) in zip(names, s["insts"]):
            L.append("%s:   ; %s" % (lbl, iname))
            L.append("        db %d,%d,%d" % (mix, len(env), loop))
            L.append("        db " + ",".join(str(((o & 15) << 4) | (v & 15)) for o, v in env))
        for data, lbl in s["streams"].items():
            L.append("%s:" % lbl)
            for i in range(0, len(data), 24):
                L.append("        db " + ",".join(str(b) for b in data[i:i + 24]))
        L.append("music_%s_end:" % n)
        sizes[n] = 8 + len(s["order"]) + 2 + 6 * len(s["patterns"]) + 32 + sum(3 + len(e) for _, _, _, e in s["insts"]) + sum(len(d) for d in s["streams"])
    return "\n".join(L) + "\n", sizes

def main():
    songs = []
    for mod in ("track_menu", "track_game"):
        songs.append(compile_song(importlib.import_module(mod).SONG))
    text, sizes = emit(songs)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    model = {}
    for s in songs:
        model[s["name"]] = dict(speed=s["speed"], rows=s["rows"], rows_total=s["rows_total"], order=s["order"], loop=s["loop"],
                                n_patterns=len(s["patterns"]), n_streams=len(s["streams"]), bytes=sizes[s["name"]],
                                frames_per_loop=s["rows_total"] * s["speed"],
                                chans=[[{k: v for k, v in r.items()} for r in ch] for ch in s["chans"]])
    (ROOT / "build").mkdir(exist_ok=True)
    (ROOT / "build/music_model.json").write_text(json.dumps(model))
    print("music_data.asm: notes table 256 B; " + "; ".join("%s %d B (%d patterns, %d streams, loop %d frames = %.1f s)" % (
        s["name"], sizes[s["name"]], len(s["patterns"]), len(s["streams"]), s["rows_total"] * s["speed"], s["rows_total"] * s["speed"] / 50) for s in songs))

if __name__ == "__main__":
    main()
