#!/usr/bin/env python3
"""patch_mt.py - rewrite the snd_menu_tick section of beeper.asm (T3 lane helper; never sed on asm)."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
ASM = ROOT / "src/common/beeper.asm"
src = ASM.read_text()
a = src.index("; ---------------------------------------------------------------- snd_menu_tick (engine tick tune)")
b = src.index("; ---- GENERATED BY tools/music/gen_beeper.py")
new = r"""; ---------------------------------------------------------------- snd_menu_tick (engine tick tune)
; One burst per call. Voice counters and the speaker level carry over between calls, so the bursts are
; consecutive slices of the same 2-voice (XOR-mixed) square wave; the gap between bursts is silence.
; Burst length = mt_inner iterations (45 T each, +25 T per speaker toggle) + mt_outer * 256 iterations.
; Defaults (contract, <= 3,000 T): mt_inner = MT_ITER, mt_outer = 0 -> ~0.65 ms blip per frame.
; A menu loop with spare time may set mt_outer = 3 (~37,000 T, ~10.5 ms of real 2-voice music per frame).
MT_SPEED equ 12                 ; frames per step (eighth note) -> 125 bpm
MT_ITER  equ 50

snd_menu_tick:
        ld a,(snd_playing)
        or a
        ret z
        ld a,(opt_music)
        or a
        jr z,snd_mus_off        ; option switched off while playing: stop + silence
        ld hl,mt_cnt
        dec (hl)
        jr nz,mt_burst
        ld (hl),MT_SPEED
        ld a,(mt_pos)
        inc a
        cp MT_LEN
        jr c,mt_pos_ok
        xor a
mt_pos_ok:
        ld (mt_pos),a
        ld hl,mt_mel            ; voice 1: one counter byte per 1/8 (0 = rest)
        call mt_addhl
        ld a,(hl)
        ld de,mt_p1
        ld hl,mt_m1+1
        call mt_setnote
        ld a,(mt_pos)
        srl a                   ; voice 2: one counter byte per 1/4
        ld hl,mt_v2
        call mt_addhl
        ld a,(hl)
        ld de,mt_p2
        ld hl,mt_m2+1
        call mt_setnote
mt_burst:
        ld hl,mt_p1
        ld a,(hl)
        inc hl
        ld c,(hl)
        inc hl
        ld d,(hl)
        inc hl
        ld e,(hl)
        inc hl
        ld h,a                  ; H = period 1, C = counter 1, D = period 2, E = counter 2
        ld a,(mt_out)
        ld l,a                  ; L = speaker level
        ld a,(mt_outer)
        ld (mt_oc),a
        ld a,(mt_inner)
        ld b,a
mt_lp:  dec c                   ; voice 1 counter          4
        jr nz,mt_l1             ;                          12/7
        ld c,h
        ld a,l
mt_m1:  xor 16                  ; mask 16 = sounding, 0 = rest (self-modified)
        ld l,a
        out (254),a
mt_l1:  dec e                   ; voice 2 counter          4
        jr nz,mt_l2             ;                          12/7
        ld e,d
        ld a,l
mt_m2:  xor 16
        ld l,a
        out (254),a
mt_l2:  djnz mt_lp              ;                          13/8  -> 45 T per silent iteration
        ld a,(mt_oc)            ; extra 256-iteration blocks (default 0)
        or a
        jr z,mt_end
        dec a
        ld (mt_oc),a
        jr mt_lp                ; B = 0 -> 256 more iterations
mt_end: ld a,c
        ld (mt_c1),a
        ld a,e
        ld (mt_c2),a
        ld a,l
        ld (mt_out),a
        ret

mt_addhl:                       ; HL = HL + A
        add a,l
        ld l,a
        ret nc
        inc h
        ret

mt_setnote:                     ; A = counter (0 = rest), DE -> period slot (+1 = counter), HL -> xor mask slot
        or a
        jr z,mt_rest
        ld (hl),16
        ld (de),a
        inc de
        ld a,1
        ld (de),a               ; counter = 1 -> the new note starts on the first iteration
        ret
mt_rest:
        ld (hl),a               ; mask 0: the voice stays silent (counter keeps running, harmless)
        ret

snd_playing:
        db 0
mt_pos: db 0
mt_cnt: db 1
mt_p1:  db 2                    ; keep the 4 bytes mt_p1, mt_c1, mt_p2, mt_c2 contiguous (mt_burst reads them in order)
mt_c1:  db 1
mt_p2:  db 2
mt_c2:  db 1
mt_out: db 0
mt_oc:  db 0
mt_inner:
        db MT_ITER
mt_outer:
        db 0

"""
src = src[:a] + new + src[b:]
old_music = src[src.index("        ld (snd_playing),a\n"):src.index("snd_mus_off:")]
new_music = """        ld (snd_playing),a
        ld a,MT_LEN-1
        ld (mt_pos),a           ; first tick advances to step 0
        ld a,1
        ld (mt_cnt),a           ; ... immediately
        ld hl,mt_m1+1
        xor a
        ld (hl),a               ; both voices muted until the first step is fetched
        ld hl,mt_m2+1
        ld (hl),a
        ld (mt_out),a
        ret
"""
src = src.replace(old_music, new_music)
hdr_a = src.index(";   snd_menu_tick")
hdr_b = src.index(";   snd_isr")
src = src[:hdr_a] + """;   snd_menu_tick call once per frame from the menu loop: non-blocking, <= 3,000 T with the default knobs
;                 (measured by tools/test_sound.py, numbers in build/t3_report.md). Plays one short burst of the
;                 2-voice (XOR-mixed) square wave per call; voice phases carry over between calls. Steps the
;                 16-bar tune every MT_SPEED frames. Knobs (bytes, caller may change them): mt_inner (loop
;                 iterations, 45 T each) and mt_outer (extra 256-iteration blocks). Default 50/0 = ~0.65 ms
;                 blip per frame (melody contour audible as a 50 Hz buzz with moving formant);
;                 mt_outer=3 = ~37,000 T/frame = ~10.5 ms of proper 2-voice music per frame.
""" + src[hdr_b:]
ASM.write_text(src)
print("patched", ASM)
