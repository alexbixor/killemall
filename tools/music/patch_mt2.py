#!/usr/bin/env python3
"""patch_mt2.py - T3: snd_menu_tick v3 - time-multiplexed 2-voice mixing (each loop pass outputs voice 1 then voice 2;
~44 kHz carrier -> the speaker's average is the true sum of both square waves, so both fundamentals are present).
Replaces the XOR mix (which only produced intermodulation products: a XOR b of bipolar squares = -a*b)."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
ASM = ROOT / "src/common/beeper.asm"
src = ASM.read_text()
a = src.index("; ---------------------------------------------------------------- snd_menu_tick (engine tick tune)")
b = src.index("; ---- GENERATED BY tools/music/gen_beeper.py")
new = r"""; ---------------------------------------------------------------- snd_menu_tick (engine tick tune)
; One burst per call. The burst loop alternates the speaker between voice 1's level and voice 2's level every pass
; (79 T, i.e. a ~44 kHz carrier the speaker cannot follow), so the audible output is the SUM of the two square waves.
; Voice counters and levels carry over between calls: the bursts are consecutive slices of the same 2-voice waveform.
; Burst length = mt_inner passes (79 T each, +14 T per voice toggle) + mt_outer * 256 passes.
; Defaults (contract, <= 3,000 T): mt_inner = MT_ITER, mt_outer = 0 -> ~0.7 ms of sound per 20 ms frame: a 50 Hz
; buzz whose spectrum follows the tune (pitch contour only). mt_outer = 2 (~43,500 T, 12.4 ms per frame) gives real
; 2-voice music; the 48K menu loop (no 3D rendering) can afford it - T2/T6 decide.
MT_SPEED equ 12                 ; frames per step (eighth note) -> 125 bpm
MT_ITER  equ 32

snd_menu_tick:
        ld a,(snd_playing)
        or a
        ret z
        ld a,(opt_music)
        or a
        jr z,snd_mus_off        ; option switched off while playing: stop + silence
        ld hl,mt_cnt
        dec (hl)
        jr nz,mt_burst
        ld (hl),MT_SPEED
        ld a,(mt_pos)
        inc a
        cp MT_LEN
        jr c,mt_pos_ok
        xor a
mt_pos_ok:
        ld (mt_pos),a
        ld hl,mt_mel            ; voice 1: one counter byte per 1/8 (0 = rest)
        call mt_addhl
        ld a,(hl)
        ld de,mt_p1
        ld hl,mt_m1+1
        call mt_setnote
        ld a,(mt_pos)
        srl a                   ; voice 2: one counter byte per 1/4
        ld hl,mt_v2
        call mt_addhl
        ld a,(hl)
        ld de,mt_p2
        ld hl,mt_m2+1
        call mt_setnote
mt_burst:
        ld hl,mt_p1
        ld a,(hl)
        inc hl
        ld c,(hl)
        inc hl
        ld d,(hl)
        inc hl
        ld e,(hl)
        inc hl
        ld h,a                  ; H = period 1, C = counter 1, D = period 2, E = counter 2
        ld a,(mt_out1)
        ld l,a                  ; L = voice 1 level (0 / 16)
        ex af,af'
        push af                 ; preserve the caller's AF'
        ld a,(mt_out2)          ; A' = voice 2 level (0 / 16)
        ex af,af'
        ld a,(mt_outer)
        ld (mt_oc),a
        ld a,(mt_inner)
        ld b,a
mt_lp:  dec c                   ; voice 1 counter          4
        jr nz,mt_l1             ;                          12/7
        ld c,h
        ld a,l
mt_m1:  xor 16                  ; 16 = sounding, 0 = rest (self-modified)
        ld l,a
mt_l1:  ld a,l                  ;                          4
        out (254),a             ; voice 1 slot             11
        dec e                   ; voice 2 counter          4
        jr nz,mt_l2             ;                          12/7
        ld e,d
        ex af,af'
mt_m2:  xor 16
        ex af,af'
mt_l2:  ex af,af'               ;                          4
        out (254),a             ; voice 2 slot             11
        ex af,af'               ;                          4
        djnz mt_lp              ;                          13/8  -> 79 T per pass without toggles
        ld a,(mt_oc)            ; extra 256-pass blocks (default 0)
        or a
        jr z,mt_end
        dec a
        ld (mt_oc),a
        jr mt_lp                ; B = 0 -> 256 more passes
mt_end: ld a,c
        ld (mt_c1),a
        ld a,e
        ld (mt_c2),a
        ld a,l
        ld (mt_out1),a
        ex af,af'
        ld (mt_out2),a
        pop af
        ex af,af'
        ret

mt_addhl:                       ; HL = HL + A
        add a,l
        ld l,a
        ret nc
        inc h
        ret

mt_setnote:                     ; A = counter (0 = rest), DE -> period slot (+1 = counter), HL -> xor mask slot
        or a
        jr z,mt_rest
        ld (hl),16
        ld (de),a
        inc de
        ld a,1
        ld (de),a               ; counter = 1 -> the new note starts on the first pass
        ret
mt_rest:
        ld (hl),a               ; mask 0: the voice stays silent (counter keeps running, harmless)
        ret

snd_playing:
        db 0
mt_pos: db 0
mt_cnt: db 1
mt_p1:  db 2                    ; keep the 4 bytes mt_p1, mt_c1, mt_p2, mt_c2 contiguous (mt_burst reads them in order)
mt_c1:  db 1
mt_p2:  db 2
mt_c2:  db 1
mt_out1:
        db 0
mt_out2:
        db 0
mt_oc:  db 0
mt_inner:
        db MT_ITER
mt_outer:
        db 0

"""
src = src[:a] + new + src[b:]
src = src.replace("""        ld hl,mt_m1+1
        xor a
        ld (hl),a               ; both voices muted until the first step is fetched
        ld hl,mt_m2+1
        ld (hl),a
        ld (mt_out),a
        ret
""", """        ld hl,mt_m1+1
        xor a
        ld (hl),a               ; both voices muted until the first step is fetched
        ld hl,mt_m2+1
        ld (hl),a
        ld (mt_out1),a
        ld (mt_out2),a
        ret
""")
hdr_a = src.index(";   snd_menu_tick")
hdr_b = src.index(";   snd_isr")
src = src[:hdr_a] + """;   snd_menu_tick call once per frame from the menu loop: non-blocking, <= 3,000 T with the default knobs
;                 (measured by tools/test_sound.py, numbers in build/t3_report.md). Plays one short burst of a
;                 2-voice square wave per call (voices mixed by time-multiplexing the speaker at ~44 kHz, bit 4
;                 only); voice phases carry over between calls. Steps the 16-bar tune every MT_SPEED frames.
;                 Knobs (bytes, caller may change them): mt_inner (loop passes, 79 T each) and mt_outer (extra
;                 256-pass blocks). Default 32/0 = ~0.7 ms of sound per frame (pitch contour only, buzzy);
;                 mt_outer=2 = ~43,500 T/frame = 12.4 ms of proper 2-voice music per frame.
""" + src[hdr_b:]
src = src.replace("; Registers: snd_fx, snd_music, snd_menu_tick destroy AF BC DE HL. No IX/IY/alternates. Stack use: 2 bytes.",
                  "; Registers: snd_fx, snd_music, snd_menu_tick destroy AF BC DE HL (snd_menu_tick uses AF' but restores it). No IX/IY.\n; Stack use: 4 bytes.")
ASM.write_text(src)
G = ROOT / "tools/music/gen_beeper.py"
g = G.read_text()
g = g.replace("MT_ITER_T = 45         # T-states per burst-loop iteration without a toggle", "MT_ITER_T = 79         # T-states per burst-loop pass (both voices) without a toggle")
g = g.replace("MT_TOGGLE_T = 25       # extra T-states for the iteration in which a voice toggles", "MT_TOGGLE_T = 14       # extra T-states for the pass in which a voice toggles")
g = g.replace("MEL_SHIFT = -1", "MEL_SHIFT = -1         # lead B4..E6")
g = g.replace("BASS_SHIFT = -1", "BASS_SHIFT = -2        # bass G2..G4")
g = g.replace("Menu tune engine (snd_menu_tick): 2 voices XOR-mixed, loop iteration = MT_ITER_T T-states (+25 T when a voice toggles),\na voice toggles the speaker every N iterations -> half period ~ N*45 + 25 T.",
              "Menu tune engine (snd_menu_tick): 2 voices time-multiplexed, loop pass = MT_ITER_T T-states (+14 T when a voice toggles),\na voice toggles every N passes -> half period ~ N*79 + 14 T.")
g = g.replace('    out.append("; counters (45 T loop iterations per half-cycle): "', '    out.append("; counters (79 T loop passes per half-cycle): "')
G.write_text(g)
print("patched beeper.asm + gen_beeper.py")
