#!/usr/bin/env python3
"""patch_m11a.py - M1.1a flicker fix: render into a column-major back buffer (BUF = 24576, 16 byte-columns x 128-byte
stride) and copy it to the live screen in one burst (COPYBUF, generated by gen48.py) at the end of render.
One-shot patch of src/48k/kea48.asm (run once after backing up to build/kea48_m1_backup.asm)."""
import pathlib
p = pathlib.Path("/home/ubuntu/work/killemall/src/48k/kea48.asm"); t = p.read_text()

def rep(old, new, count=1):
    global t
    assert t.count(old) == count, (old, t.count(old))
    t = t.replace(old, new)

rep("ATTRWIN equ 22568          ; attribute address of window row 0 (attr row 1), column 8\n",
    "ATTRWIN equ 22568          ; attribute address of window row 0 (attr row 1), column 8\n"
    "BUF     equ 24576          ; back buffer: 16 byte-columns x 128-byte stride (BUF + bytecol*128 + row), 1536 bytes used\n")
rep("        ld hl,SCRWIN\n        ld b,0\n        ld de,43605\n        call CLEARW\n",
    "        ld hl,BUF\n        ld b,0\n        ld de,43605\n        call CLEARW\n")
rep("        cp 64\n        jr c,col_loop\n        ret\n",
    "        cp 64\n        jr c,col_loop\n        jp COPYBUF             ; one burst copy of the back buffer to the screen (ends with ret)\n")
rep("""; screen address of (topr, bytecol)
        ld a,(topr)
        add a,a
        ld l,a
        ld h,0
        ld de,SCRADDR
        add hl,de
        ld e,(hl)
        inc hl
        ld d,(hl)
        ld a,(bytecol)
        add a,8
        add a,e
        ld e,a
        push de
""", """; back-buffer address of (topr, bytecol) = BUF + bytecol*128 + topr
        ld a,(bytecol)
        rrca
        ld e,a
        and 7
        add a,BUF/256
        ld d,a
        ld a,e
        and 128
        ld e,a
        ld a,(topr)
        add a,e
        ld e,a
        push de
""")
rep("; kea48.asm - Kill'em All, 48K edition. Milestone M1: textured raycaster, movement, fps counter.\n",
    "; kea48.asm - Kill'em All, 48K edition. Milestone M1.1a: M1 renderer drawing into a back buffer, copied once per frame.\n")
p.write_text(t)
print("patched", p)
