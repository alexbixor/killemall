#!/usr/bin/env python3
"""spritec.py - Kill'em all sprite compiler (lane T5).  Text-art or PNG in, Z80 data out in the ARCH_M2 format.

Input: assets/sprites/NN_name.txt   NN = sprite id 00..17 (order of spr_table), 16 chars per row (32 for weapons 14..17)
       '#' = set pixel (ink, opaque)   'o' = opaque black (mask 0, pixel 0 - used for outlines/fills)
       '.' or ' ' = transparent        ';' at line start = comment line
       (a .png with the same name is accepted too: white = '#', black = 'o', anything else/alpha 0 = transparent)
Heights: sprites 8..24 rows, weapons exactly 24 rows (32 px wide).

Output src/gen/sprites_data.asm:
  spr_table: dw spr_00 .. spr_17           (18 entries, ids as in ARCH_M2.md)
  spr_NN:    db H ; then for byte-column 0..(W/8-1): H mask bytes (bit 1 = transparent) then H pixel bytes
  Row 0 is the TOP row.  Bit 7 = leftmost pixel.  Draw = (screen AND mask) OR pixel.
Also: build/sprites_sheet.png contact sheet (x4) and a size report.  Deterministic.

usage: spritec.py [assets/sprites] [src/gen/sprites_data.asm] [build/sprites_sheet.png]
       spritec.py --set assets/sprites_m4 --out build/sprites_m4_data.asm --sheet build/sprites_m4_sheet.png
         (M4 set mode, lane E 5 Nov 2026: any contiguous id range 00..NN, names from the file names, weapons = 32 px
          wide files; the positional/default mode above is untouched and stays byte-identical.)
"""
import sys, re, pathlib

NAMES = ['imp walk A', 'imp walk B', 'imp attack', 'imp dead', 'zombie walk A', 'zombie walk B', 'zombie attack',
         'zombie dead', 'health', 'ammo', 'red key', 'blue key', 'barrel', 'lamp',
         'pistol idle', 'pistol fire', 'shotgun idle', 'shotgun fire']
WEAPON_IDS = {14, 15, 16, 17}

def load_text(path):
    rows = []
    for line in pathlib.Path(path).read_text().splitlines():
        if line.startswith(';') or line.strip() == '':
            continue
        rows.append(line.rstrip('\n'))
    return rows

def load_png(path):
    from PIL import Image
    img = Image.open(path).convert('RGBA'); w, h = img.size; px = img.load(); rows = []
    for y in range(h):
        r = ''
        for x in range(w):
            R, G, B, A = px[x, y]
            r += '.' if A < 128 else ('#' if (R + G + B) > 384 else 'o')
        rows.append(r)
    return rows

def compile_sprite(sid, rows, src):
    W = 32 if sid in WEAPON_IDS else 16
    H = len(rows)
    if sid in WEAPON_IDS:
        assert H == 24, f"{src}: weapon must be 24 rows, got {H}"
    else:
        assert 8 <= H <= 24, f"{src}: height {H} not in 8..24"
    for y, r in enumerate(rows):
        r = r.ljust(W)
        assert len(r) == W, f"{src}: row {y} is {len(r)} chars, need {W}"
        for ch in r:
            assert ch in '#o. ', f"{src}: bad char {ch!r} in row {y}"
        rows[y] = r
    cols = W // 8
    data = bytearray([H])
    for c in range(cols):
        masks = []; pixels = []
        for y in range(H):
            m = 0; p = 0
            for b in range(8):
                ch = rows[y][c * 8 + b]
                bit = 0x80 >> b
                if ch == '#': p |= bit
                elif ch == 'o': pass
                else: m |= bit
            masks.append(m); pixels.append(p)
        data += bytes(masks) + bytes(pixels)
    assert len(data) == 1 + cols * 2 * H
    return W, H, bytes(data)

def fmt_db(bs):
    return '\n'.join('    db ' + ','.join(f'${b:02X}' for b in bs[i:i + 12]) for i in range(0, len(bs), 12))

def main(src_dir='assets/sprites', out_asm='src/gen/sprites_data.asm', sheet='build/sprites_sheet.png'):
    src_dir = pathlib.Path(src_dir)
    files = {}
    for p in sorted(src_dir.iterdir()):
        m = re.match(r'(\d\d)_', p.name)
        if m and p.suffix in ('.txt', '.png'):
            sid = int(m.group(1))
            assert sid not in files, f"duplicate id {sid}: {p} and {files[sid]}"
            files[sid] = p
    assert sorted(files) == list(range(18)), f"need ids 00..17, got {sorted(files)}"
    sprites = []
    for sid in range(18):
        p = files[sid]
        rows = load_png(p) if p.suffix == '.png' else load_text(p)
        W, H, data = compile_sprite(sid, rows, p)
        sprites.append((sid, p, W, H, rows, data))
    lines = ['; sprites_data.asm - generated by tools/spritec.py from assets/sprites/*.txt (lane T5). DO NOT EDIT.',
             '; Format (ARCH_M2.md): per sprite db H, then per byte-column (0..W/8-1): H mask bytes (bit 1 = transparent)',
             '; then H pixel bytes. Row 0 = top row, bit 7 = leftmost pixel. draw = (screen AND mask) OR pixel.',
             '; Sprites (ids 0..13) are 16 px wide, weapons (14..17) 32x24. Shorter sprites (items) are meant to be',
             '; drawn standing on the floor (bottom-aligned to the 24-row enemy box); corpses live in the bottom rows.',
             '', 'spr_table:']
    lines.append('    dw ' + ','.join(f'spr_{s[0]:02d}' for s in sprites))
    total = 2 * 18
    for sid, p, W, H, rows, data in sprites:
        lines.append(f'spr_{sid:02d}: ; id {sid} {NAMES[sid]} {W}x{H} {len(data)} bytes ({p.name})')
        lines.append(f'    db {H}')
        lines.append(fmt_db(data[1:]))
        total += len(data)
    lines.append('spr_data_end:')
    lines.append(f'; total sprite+weapon data incl. spr_table: {total} bytes')
    pathlib.Path(out_asm).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(out_asm).write_text('\n'.join(lines) + '\n')
    for sid, p, W, H, rows, data in sprites:
        print(f'id {sid:2d} {NAMES[sid]:14s} {W:2d}x{H:2d} {len(data):4d} B  {p.name}')
    print(f'total (18 sprites + table): {total} bytes  -> {out_asm}')
    if sheet:
        render_sheet(sprites, sheet)
    return total

def render_sheet(sprites, out, scale=4, names=NAMES, per_row=6):
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.load_default()
    cell_w = 32 * scale + 16; cell_h = 24 * scale + 28
    rows = (len(sprites) + per_row - 1) // per_row
    img = Image.new('RGB', (per_row * cell_w + 8, rows * cell_h + 8), (40, 40, 48))
    d = ImageDraw.Draw(img)
    for i, (sid, p, W, H, rws, data) in enumerate(sprites):
        ox = 8 + (i % per_row) * cell_w; oy = 8 + (i // per_row) * cell_h
        # checkered transparent background in the sprite box
        for y in range(H):
            for x in range(W):
                ch = rws[y][x]
                col = (90, 90, 100) if (x // 4 + y // 4) % 2 else (70, 70, 80)
                if ch == '#': col = (240, 240, 240)
                elif ch == 'o': col = (0, 0, 0)
                d.rectangle((ox + x * scale, oy + y * scale, ox + x * scale + scale - 1, oy + y * scale + scale - 1), fill=col)
        d.text((ox, oy + 24 * scale + 4), f'{sid} {names[sid]} {W}x{H}', fill=(255, 230, 120), font=font)
    img.save(out)
    print(f'{out}: {img.size[0]}x{img.size[1]} contact sheet (x{scale})')

# ---------------------------------------------------------------------------------------------------------------------
# M4 set mode (lane E, 5 Nov 2026): `--set DIR --out FILE.asm [--sheet FILE.png]`.
# Same per-sprite byte format as above.  Differences: ids are whatever contiguous range 00..NN the directory holds, the
# name comes from the file name (NN_some_name.txt -> 'some name'), a sprite is a 32-px weapon when its first data row is
# 32 chars wide (weapons must be 24 rows, like ids 14..17), and the labels/table symbol carry a 'm4' prefix so this file
# can be assembled next to src/gen/sprites_data.asm.  main() above is NOT touched: the default run stays byte-identical.
def compile_sprite_w(sid, rows, src, W):
    H = len(rows)
    if W == 32:
        assert H == 24, f"{src}: weapon must be 24 rows, got {H}"
    else:
        assert 8 <= H <= 24, f"{src}: height {H} not in 8..24"
    for y, r in enumerate(rows):
        r = r.ljust(W)
        assert len(r) == W, f"{src}: row {y} is {len(r)} chars, need {W}"
        for ch in r:
            assert ch in '#o. ', f"{src}: bad char {ch!r} in row {y}"
        rows[y] = r
    cols = W // 8
    data = bytearray([H])
    for c in range(cols):
        masks = []; pixels = []
        for y in range(H):
            m = 0; p = 0
            for b in range(8):
                ch = rows[y][c * 8 + b]
                bit = 0x80 >> b
                if ch == '#': p |= bit
                elif ch == 'o': pass
                else: m |= bit
            masks.append(m); pixels.append(p)
        data += bytes(masks) + bytes(pixels)
    assert len(data) == 1 + cols * 2 * H
    return W, H, bytes(data)

def main_set(src_dir, out_asm, sheet=None, prefix='m4'):
    src_dir = pathlib.Path(src_dir)
    files = {}
    for p in sorted(src_dir.iterdir()):
        m = re.match(r'(\d\d)_(.*)', p.stem)
        if m and p.suffix in ('.txt', '.png'):
            sid = int(m.group(1))
            assert sid not in files, f"duplicate id {sid}: {p} and {files[sid]}"
            files[sid] = p
    n = len(files)
    assert n and sorted(files) == list(range(n)), f"need contiguous ids 00..{n - 1}, got {sorted(files)}"
    sprites = []; names = []
    for sid in range(n):
        p = files[sid]
        rows = load_png(p) if p.suffix == '.png' else load_text(p)
        W = 32 if len(rows[0].rstrip()) > 16 else 16
        W, H, data = compile_sprite_w(sid, rows, p, W)
        sprites.append((sid, p, W, H, rows, data))
        names.append(re.match(r'\d\d_(.*)', p.stem).group(1).replace('_', ' '))
    lines = [f'; {pathlib.Path(out_asm).name} - generated by tools/spritec.py --set {src_dir} (lane E, M4 set). DO NOT EDIT.',
             '; Format (ARCH_M2.md): per sprite db H, then per byte-column (0..W/8-1): H mask bytes (bit 1 = transparent)',
             '; then H pixel bytes. Row 0 = top row, bit 7 = leftmost pixel. draw = (screen AND mask) OR pixel.',
             f'; Enemies/items are 16 px wide, weapons 32x24. Ids 0..17 = today\'s set (src/gen/sprites_data.asm), 18.. = M4.',
             '; Walkers stand on the bottom row of the 24-row box; floaters (22..24) leave 2 empty bottom rows; corpses <= 8 rows.',
             '', f'spr_{prefix}_table:']
    for i in range(0, n, 18):
        lines.append('    dw ' + ','.join(f'spr_{prefix}_{s[0]:02d}' for s in sprites[i:i + 18]))
    total = 2 * n
    for sid, p, W, H, rows, data in sprites:
        lines.append(f'spr_{prefix}_{sid:02d}: ; id {sid} {names[sid]} {W}x{H} {len(data)} bytes ({p.name})')
        lines.append(f'    db {H}')
        lines.append(fmt_db(data[1:]))
        total += len(data)
    lines.append(f'spr_{prefix}_data_end:')
    lines.append(f'; total sprite+weapon data incl. spr_{prefix}_table: {total} bytes ({n} sprites)')
    pathlib.Path(out_asm).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(out_asm).write_text('\n'.join(lines) + '\n')
    for sid, p, W, H, rows, data in sprites:
        print(f'id {sid:2d} {names[sid]:18s} {W:2d}x{H:2d} {len(data):4d} B  {p.name}')
    new = [s for s in sprites if s[0] >= 18]
    print(f'total ({n} sprites + table): {total} bytes  -> {out_asm}')
    print(f'ids 18..{n - 1} only (the new M4 data): {sum(len(s[5]) for s in new)} bytes + {2 * len(new)} table bytes')
    if sheet:
        render_sheet(sprites, sheet, names=names)
    return total

def parse_set_args(a):
    opts = {'--set': None, '--out': None, '--sheet': None}
    i = 0
    while i < len(a):
        assert a[i] in opts and i + 1 < len(a), f"usage: --set DIR --out FILE.asm [--sheet FILE.png]; got {a}"
        opts[a[i]] = a[i + 1]; i += 2
    assert opts['--set'] and opts['--out'], "--set and --out are both required"
    return opts

if __name__ == '__main__':
    a = sys.argv[1:]
    if '--set' in a:
        o = parse_set_args(a)
        main_set(o['--set'], o['--out'], o['--sheet'])
    else:
        main(*a)
