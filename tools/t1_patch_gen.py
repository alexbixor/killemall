#!/usr/bin/env python3
"""t1_patch_gen.py - append the T1 sprite generator to tools/gen48.py (idempotent)."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
P = ROOT / "tools/gen48.py"
s = P.read_text()
if "def sprites48" in s:
    raise SystemExit("already patched")
(ROOT / "build/gen48_pre_t1a.py").write_text(s)
add = r'''
# ---------------------------------------------------------------- T1: sprites (consumes T5 src/gen/sprites_data.asm)
SPRSRC = pathlib.Path(__file__).resolve().parent.parent / "src" / "gen" / "sprites_data.asm"

def parse_sprites():
    """T5 format: spr_NN: label, db H, then W/8 byte-columns x (H mask bytes, H pixel bytes). Returns {id: (H, bytes)}."""
    out, cur, acc = {}, None, []
    for line in SPRSRC.read_text().splitlines():
        t = line.split(";")[0].strip()
        if t.startswith("spr_") and t[4:6].isdigit() and ":" in t:
            if cur is not None: out[cur] = (acc[0], bytes(acc[1:]))
            cur, acc = int(t[4:6]), []
        elif cur is not None and (t.startswith("db ") or t.startswith("defb ")):
            for v in t.split(None, 1)[1].split(","):
                v = v.strip()
                if v: acc.append(int(v[1:], 16) if v.startswith("$") else int(v))
    if cur is not None: out[cur] = (acc[0], bytes(acc[1:]))
    return out

def transpose16(h, data, box=24):
    """16-px sprite -> per column u: m0 p0 m1 p1 m2 p2 (vertical bit strips, bit 7 = top row of each 8-row group).
    Rows above the art (box - h) are transparent (mask 1, pix 0); the art is bottom aligned."""
    out = []
    for u in range(16):
        bc, bit = u >> 3, 7 - (u & 7)
        mask_bytes = data[bc * 2 * h: bc * 2 * h + h]; pix_bytes = data[bc * 2 * h + h: bc * 2 * h + 2 * h]
        m = [1] * (box - h) + [(b >> bit) & 1 for b in mask_bytes]
        p = [0] * (box - h) + [(b >> bit) & 1 for b in pix_bytes]
        for k in range(box // 8):
            mb = sum(m[8 * k + i] << (7 - i) for i in range(8)); pb = sum(p[8 * k + i] << (7 - i) for i in range(8))
            out += [mb, pb]
    return out

def sprites48():
    """gen/sprites48.asm: spr_table (ids 0..17), ids 0..13 transposed 96-byte strips, weapons 14..17 verbatim (db 24 + data),
    NCTAB[hcol] = sprite width in ray columns (hcol/3), STEPTAB[nc] = u step 8.8 (16*256/nc)."""
    if not SPRSRC.exists():
        spr = {i: (24, bytes([0xFF] * 24 + [0xAA, 0x55] * 12) * 2) for i in range(14)}        # placeholder boxes
        spr.update({i: (24, bytes([0] * 96) * 2) for i in range(14, 18)})
    else:
        spr = parse_sprites()
    s = ["; generated by tools/gen48.py (T1) from src/gen/sprites_data.asm - do not edit", "spr_table:",
         "        defw " + ",".join("spr_%d" % i for i in range(18))]
    for i in range(14):
        h, data = spr.get(i, (24, bytes(96)))
        s += ["spr_%d:" % i, db(transpose16(h, data))]
    for i in range(14, 18):
        h, data = spr.get(i, (24, bytes(192)))
        s += ["spr_%d:" % i, "        defb %d" % h, db(list(data))]
    nctab = [min(64, round(hc / 3)) for hc in range(193)]
    steptab = [0] + [min(65535, round(16 * 256 / nc)) for nc in range(1, 65)]
    s += ["NCTAB:", db(nctab), "STEPTAB:", dw(steptab)]
    (OUT / "sprites48.asm").write_text("\n".join(s) + "\n")
'''
s = s.replace('\nif __name__ == "__main__":\n    tables(); unrolled(); dda()\n',
              add + '\nif __name__ == "__main__":\n    tables(); unrolled(); dda(); sprites48()\n')
P.write_text(s)
print("patched gen48.py")
