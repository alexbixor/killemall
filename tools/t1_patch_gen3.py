#!/usr/bin/env python3
"""t1_patch_gen3.py - compact low-block layout: page tables first (no ALIGN), hv capped at 128 (NCTAB 129, VSTEP 65)."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
P = ROOT / "tools/gen48.py"
s = P.read_text()
old_hdr = '''    s = ["; generated by tools/gen48.py (T1) from src/gen/sprites_data.asm - do not edit",
         "        org 27904              ; T1: sprite data, SCHAIN, tables and the level live in the free low block 27904..32767",
         "spr_table:",
         "        defw " + ",".join("spr_%d" % i for i in range(18))]
'''
new_hdr = '''    nctab = [max(1, min(64, round(hc / 3))) if hc else 0 for hc in range(129)]
    steptab = [0] + [min(65535, round(16 * 256 / nc)) for nc in range(1, 65)]
    vstep = [round(hv * 256 / 24) for hv in range(0, 130, 2)]
    s = ["; generated by tools/gen48.py (T1) from src/gen/sprites_data.asm - do not edit",
         "        org 27904              ; T1: page tables, sprite data, SCHAIN and the level live in the free low block 27904..32767",
         "SPG:", "ROWTAB:", "        defs 50",
         "CHJ:", "        defw " + ",".join("SCHAIN_END-%d" % (5 * n) for n in range(97)),
         "NCTAB:", db(nctab), "STEPTAB:", dw(steptab), "VSTEP:", dw(vstep),
         "spr_table:",
         "        defw " + ",".join("spr_%d" % i for i in range(18))]
'''
assert old_hdr in s
s = s.replace(old_hdr, new_hdr)
old_tail = '''    s += ["SCHAIN_END:", "        ret", ALIGN256, "SPG:", "ROWTAB:", "        defs 50",
          "CHJ:", "        defw " + ",".join("SCHAIN_END-%d" % (5 * n) for n in range(97))]
    nctab = [max(1, min(64, round(hc / 3))) if hc else 0 for hc in range(193)]
    steptab = [0] + [min(65535, round(16 * 256 / nc)) for nc in range(1, 65)]
    vstep = [round(hv * 256 / 24) for hv in range(0, 194, 2)]
    s += ["NCTAB:", db(nctab), "STEPTAB:", dw(steptab), "VSTEP:", dw(vstep)]
'''
assert old_tail in s
s = s.replace(old_tail, '    s += ["SCHAIN_END:", "        ret"]\n')
P.write_text(s)
# cap hv right after perp_h in thing_xform2
C = ROOT / "src/common/sprites_c.asm"
t = C.read_text()
old = "        cp 6\n        ret c                  ; too small to see\n        ld (thv),a\n"
assert old in t
t = t.replace(old, "        cp 6\n        ret c                  ; too small to see\n        cp 129\n        jr c,$+4\n        ld a,128               ; cap (CPU bound, NCTAB/VSTEP sized for it)\n        ld (thv),a\n")
C.write_text(t)
print("ok")
